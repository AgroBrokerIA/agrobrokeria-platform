create table if not exists public.destinos_homologados(
 id_destino bigint generated by default as identity primary key,
 tipo public.tipo_destino_grano not null,
 nombre_establecimiento varchar(150) not null,
 localidad varchar(100) not null,
 provincia varchar(50) not null default 'Santa Fe',
 cuit_operador varchar(11),
 verificado boolean not null default false,
 activo boolean not null default true,
 fuente_datos text not null default 'carga_inicial_usuario',
 creado_en timestamptz not null default now(),
 actualizado_en timestamptz not null default now(),
 constraint destinos_homologados_cuit_chk check(cuit_operador is null or cuit_operador ~ '^[0-9]{11}$'),
 constraint destinos_homologados_unique unique(tipo,nombre_establecimiento,localidad,provincia)
);
create index if not exists destinos_homologados_tipo_activo_idx on public.destinos_homologados(tipo,activo,nombre_establecimiento);
alter table public.destinos_homologados enable row level security;
revoke all on public.destinos_homologados from anon,public;
grant select on public.destinos_homologados to authenticated;
drop policy if exists destinos_homologados_select_active on public.destinos_homologados;
create policy destinos_homologados_select_active on public.destinos_homologados for select to authenticated using(activo=true);
drop policy if exists destinos_homologados_admin_insert on public.destinos_homologados;
create policy destinos_homologados_admin_insert on public.destinos_homologados for insert to authenticated with check(public.es_administrador_plataforma());
drop policy if exists destinos_homologados_admin_update on public.destinos_homologados;
create policy destinos_homologados_admin_update on public.destinos_homologados for update to authenticated using(public.es_administrador_plataforma()) with check(public.es_administrador_plataforma());
drop policy if exists destinos_homologados_admin_delete on public.destinos_homologados;
create policy destinos_homologados_admin_delete on public.destinos_homologados for delete to authenticated using(public.es_administrador_plataforma());

