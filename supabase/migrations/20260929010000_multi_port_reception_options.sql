update public.publicaciones
set puertos = case
  when coalesce(puerto,'') <> '' and cardinality(coalesce(puertos,'{}'::text[])) = 0 then array[puerto]
  else coalesce(puertos,'{}'::text[])
end;

create or replace function public.guardar_publicacion(p_publicacion_id uuid, p_datos jsonb)
returns uuid
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_uid uuid := auth.uid();
  v_empresa uuid;
  v_id uuid;
  v_existing_empresa uuid;
  v_puertos text[];
  v_lugares text[];
begin
  if v_uid is null then raise exception 'No autenticado'; end if;
  select active_company_id into v_empresa from public.profiles where id=v_uid;
  if v_empresa is null or not exists (select 1 from public.company_users where company_id=v_empresa and profile_id=v_uid and activo=true) then
    raise exception 'Empresa activa inválida';
  end if;

  v_puertos := case when p_datos ? 'puertos'
    then coalesce((select array_agg(value order by value) from jsonb_array_elements_text(coalesce(p_datos->'puertos','[]'::jsonb))), '{}'::text[])
    else '{}'::text[] end;

  v_lugares := case when p_datos ? 'lugares_recepcion'
    then coalesce((select array_agg(value order by value) from jsonb_array_elements_text(coalesce(p_datos->'lugares_recepcion','[]'::jsonb))), '{}'::text[])
    else '{}'::text[] end;

  if p_publicacion_id is null then
    if coalesce((p_datos->>'cantidad_tn')::numeric,0)<=0 or coalesce((p_datos->>'precio_tn')::numeric,0)<=0 then
      raise exception 'Cantidad y precio deben ser mayores a cero';
    end if;

    insert into public.publicaciones(
      empresa_id,tipo,producto_id,cantidad_tn,precio_tn,moneda_id,incoterm_id,provincia,localidad,
      puerto,puertos,lugares_recepcion,calidad,humedad,proteina,observaciones,estado
    )
    values(
      v_empresa,p_datos->>'tipo',(p_datos->>'producto_id')::integer,(p_datos->>'cantidad_tn')::numeric,
      (p_datos->>'precio_tn')::numeric,(p_datos->>'moneda_id')::integer,(p_datos->>'incoterm_id')::integer,
      p_datos->>'provincia',p_datos->>'localidad',
      coalesce(nullif(p_datos->>'puerto',''),nullif(v_puertos[1],'')),v_puertos,v_lugares,
      nullif(p_datos->>'calidad',''),nullif(p_datos->>'humedad','')::numeric,
      nullif(p_datos->>'proteina','')::numeric,nullif(p_datos->>'observaciones',''),'PUBLICADA'
    )
    returning id into v_id;
  else
    select empresa_id into v_existing_empresa from public.publicaciones where id=p_publicacion_id for update;
    if v_existing_empresa is distinct from v_empresa then raise exception 'No autorizado'; end if;

    update public.publicaciones set
      tipo=p_datos->>'tipo',
      producto_id=(p_datos->>'producto_id')::integer,
      cantidad_tn=(p_datos->>'cantidad_tn')::numeric,
      precio_tn=(p_datos->>'precio_tn')::numeric,
      moneda_id=(p_datos->>'moneda_id')::integer,
      incoterm_id=(p_datos->>'incoterm_id')::integer,
      provincia=p_datos->>'provincia',
      localidad=p_datos->>'localidad',
      puerto=coalesce(nullif(p_datos->>'puerto',''),nullif(v_puertos[1],'')),
      puertos=v_puertos,
      lugares_recepcion=v_lugares,
      calidad=nullif(p_datos->>'calidad',''),
      humedad=nullif(p_datos->>'humedad','')::numeric,
      proteina=nullif(p_datos->>'proteina','')::numeric,
      observaciones=nullif(p_datos->>'observaciones',''),
      actualizada_en=now()
    where id=p_publicacion_id
    returning id into v_id;
  end if;
  return v_id;
end;
$function$;
