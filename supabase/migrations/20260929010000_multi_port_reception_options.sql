create table if not exists public.catalogo_puertos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  pais text not null default 'Argentina',
  provincia text,
  localidad text,
  tipo text not null default 'PORT',
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.catalogo_lugares_recepcion (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  descripcion text,
  activo boolean not null default true,
  orden integer not null default 0
);

alter table public.publicaciones
  add column if not exists puertos text[] not null default '{}'::text[],
  add column if not exists lugares_recepcion text[] not null default '{}'::text[];

